-- ============================================================================
-- Fase 1: partidas oficiais pós-T0 coletadas da API-Football.
--
-- POR QUE A COLETA É POR DATA, E NÃO POR TIME OU POR LIGA:
-- o plano gratuito responde "Free plans do not have access to this season, try
-- from 2022 to 2024" para QUALQUER consulta com ?season= — o que inclui
-- /teams?league=X&season=2026 e /fixtures?league=X&season=2026. A consulta por
-- data (/fixtures?date=YYYY-MM-DD) não tem essa trava: devolveu 965 jogos do
-- mundo inteiro em 01/08/2026, sem erro.
--
-- Ou seja, consultar por data não é apenas 40× mais econômico que consultar
-- clube a clube: é a única forma que funciona sem plano pago.
--
-- LIMITE QUE ISSO IMPÕE: a janela do plano gratuito é de ~3 dias (ontem, hoje,
-- amanhã). Não existe backfill — jogo cuja janela passou sem sincronizar está
-- perdido para sempre. Daí a rotina rodar 2×/dia e sempre reprocessar ontem.
-- ============================================================================

