CREATE TABLE IF NOT EXISTS public.club_fixtures (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider            TEXT   NOT NULL DEFAULT 'api_football',
  provider_fixture_id BIGINT NOT NULL,
  league_id           BIGINT,
  league_name         TEXT,
  round_name          TEXT,
  kickoff_at          TIMESTAMPTZ NOT NULL,
  status              TEXT NOT NULL,
  home_team_key       TEXT REFERENCES public.club_source_ids(team_key) ON UPDATE CASCADE,
  away_team_key       TEXT REFERENCES public.club_source_ids(team_key) ON UPDATE CASCADE,
  home_provider_id    BIGINT NOT NULL,
  away_provider_id    BIGINT NOT NULL,
  home_team_name      TEXT NOT NULL,
  away_team_name      TEXT NOT NULL,
  -- 90 minutos SEPARADO de prorrogação e pênaltis. A API devolve `goals` já
  -- somando a prorrogação; o tempo regulamentar puro está em score.fulltime.
  -- Misturar os dois inflaria o ataque de quem venceu na prorrogação (§6.9).
  goals_home_90       INTEGER,
  goals_away_90       INTEGER,
  goals_home_extra    INTEGER,
  goals_away_extra    INTEGER,
  penalties_home      INTEGER,
  penalties_away      INTEGER,
  venue_name          TEXT,
  model_eligible      BOOLEAN NOT NULL DEFAULT false,
  model_exclusion_reason TEXT,
  synced_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (provider, provider_fixture_id)
);

CREATE INDEX IF NOT EXISTS club_fixtures_kickoff_idx  ON public.club_fixtures (kickoff_at DESC);
CREATE INDEX IF NOT EXISTS club_fixtures_home_idx     ON public.club_fixtures (home_team_key, kickoff_at DESC);
CREATE INDEX IF NOT EXISTS club_fixtures_away_idx     ON public.club_fixtures (away_team_key, kickoff_at DESC);
CREATE INDEX IF NOT EXISTS club_fixtures_elegivel_idx ON public.club_fixtures (model_eligible, kickoff_at DESC);

ALTER TABLE public.club_fixtures ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Jogos dos clubes visiveis para todos" ON public.club_fixtures FOR SELECT USING (true);
CREATE POLICY "Admins gerenciam jogos dos clubes" ON public.club_fixtures FOR ALL USING (
  EXISTS (SELECT 1 FROM public.profiles WHERE profiles.id = auth.uid() AND profiles.is_admin = true));

